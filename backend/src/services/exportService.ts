import { Book, Draft, CanonFact, VoiceNote } from '../types/canonStudio.js';

export type ExportFormat = 'fountain' | 'markdown' | 'txt';

export interface BranchJourneyExportInput {
  storyTitle?: string;
  genre?: string;
  scenes: {
    decisionIndex: number;
    sceneText: string;
    chosenOption?: string;
    optionType?: 'bold' | 'careful' | 'unexpected';
  }[];
}

export class ExportService {
  /**
   * Export a published Book to Fountain Screenplay, Markdown, or Plain Text
   */
  public exportBook(book: Book, format: ExportFormat = 'markdown'): { content: string; filename: string; mimeType: string } {
    const slug = this.slugify(book.title || 'untitled-saga');

    if (format === 'fountain') {
      const content = this.formatBookAsFountain(book);
      return {
        content,
        filename: `${slug}.fountain`,
        mimeType: 'text/plain'
      };
    }

    if (format === 'txt') {
      const content = this.formatBookAsText(book);
      return {
        content,
        filename: `${slug}.txt`,
        mimeType: 'text/plain'
      };
    }

    // Default: Markdown
    const content = this.formatBookAsMarkdown(book);
    return {
      content,
      filename: `${slug}.md`,
      mimeType: 'text/markdown'
    };
  }

  /**
   * Export an in-progress Draft to Fountain, Markdown, or Plain Text (including Canon Facts)
   */
  public exportDraft(draft: Draft, format: ExportFormat = 'markdown'): { content: string; filename: string; mimeType: string } {
    const slug = this.slugify(draft.title || 'untitled-draft');

    if (format === 'fountain') {
      const content = this.formatDraftAsFountain(draft);
      return {
        content,
        filename: `${slug}-screenplay.fountain`,
        mimeType: 'text/plain'
      };
    }

    if (format === 'txt') {
      const content = this.formatDraftAsText(draft);
      return {
        content,
        filename: `${slug}-draft.txt`,
        mimeType: 'text/plain'
      };
    }

    // Default: Markdown
    const content = this.formatDraftAsMarkdown(draft);
    return {
      content,
      filename: `${slug}-draft.md`,
      mimeType: 'text/markdown'
    };
  }

  /**
   * Export an Interactive Branching Playthrough Journey as a Decision Tree log
   */
  public exportBranchingJourney(journey: BranchJourneyExportInput): { content: string; filename: string; mimeType: string } {
    const title = journey.storyTitle || 'Interactive Branching Saga';
    const slug = this.slugify(title);

    let md = `# 🌳 ${title}\n`;
    md += `*Genre: ${journey.genre || 'Interactive Fiction'} | Format: Non-linear Branching Journey*\n\n`;
    md += `> **Vector Memory Tree Decision Log**: Below is the verified decision path and narrative chain executed by the player.\n\n---\n\n`;

    journey.scenes.forEach((step, idx) => {
      md += `### Beat ${idx + 1} (Decision Step ${step.decisionIndex})\n\n`;
      md += `${step.sceneText}\n\n`;
      if (step.chosenOption) {
        const typeBadge = step.optionType ? `[${step.optionType.toUpperCase()}] ` : '';
        md += `> 🎯 **Player Choice**: ${typeBadge}${step.chosenOption}\n\n`;
      }
      md += `---\n\n`;
    });

    md += `\n*Generated by Canon Story Studio — Interactive Branching Engine*\n`;

    return {
      content: md,
      filename: `${slug}-branching-journey.md`,
      mimeType: 'text/markdown'
    };
  }

  // -------------------------------------------------------------
  // Internal Formatters
  // -------------------------------------------------------------
  private formatBookAsFountain(book: Book): string {
    let out = `Title: ${book.title.toUpperCase()}\n`;
    out += `Credit: Written by\n`;
    out += `Author: ${book.authorName}\n`;
    out += `Genre: ${book.genre}\n`;
    out += `Draft date: ${new Date(book.publishedAt).toLocaleDateString()}\n`;
    out += `Notes: Exported from Canon Story Studio\n\n`;
    out += `===\n\n`;

    book.episodes.forEach((ep, i) => {
      out += `\n# EPISODE ${i + 1}: ${(ep.title || 'UNTITLED').toUpperCase()}\n\n`;
      out += `${ep.content}\n\n`;
      out += `===\n\n`;
    });

    return out.trim();
  }

  private formatBookAsMarkdown(book: Book): string {
    let md = `# ${book.title}\n\n`;
    md += `**Author**: ${book.authorName}  \n`;
    md += `**Genre**: ${book.genre}  \n`;
    md += `**Published**: ${new Date(book.publishedAt).toLocaleDateString()}  \n\n`;

    if (book.blurb) {
      md += `> ${book.blurb}\n\n---\n\n`;
    }

    book.episodes.forEach((ep, i) => {
      md += `## Episode ${i + 1}: ${ep.title || `Part ${i + 1}`}\n\n`;
      md += `${ep.content}\n\n`;
      md += `---\n\n`;
    });

    md += `\n*Exported from Canon Story Studio*\n`;
    return md;
  }

  private formatBookAsText(book: Book): string {
    let txt = `=================================================================\n`;
    txt += `${book.title.toUpperCase()}\n`;
    txt += `By: ${book.authorName} | Genre: ${book.genre}\n`;
    txt += `=================================================================\n\n`;

    if (book.blurb) {
      txt += `SUMMARY:\n${book.blurb}\n\n-----------------------------------------------------------------\n\n`;
    }

    book.episodes.forEach((ep, i) => {
      txt += `EPISODE ${i + 1}: ${ep.title.toUpperCase()}\n\n`;
      txt += `${ep.content}\n\n`;
      txt += `-----------------------------------------------------------------\n\n`;
    });

    return txt;
  }

  private formatDraftAsFountain(draft: Draft): string {
    let out = `Title: ${draft.title.toUpperCase()}\n`;
    out += `Credit: Screenplay Draft\n`;
    out += `Genre: ${draft.genre}\n`;
    out += `Date: ${new Date().toLocaleDateString()}\n`;
    out += `Status: Working Draft (Canon Story Studio)\n\n`;
    out += `===\n\n`;

    draft.episodes.forEach((ep, i) => {
      out += `\n# EPISODE ${i + 1}: ${(ep.title || 'UNTITLED').toUpperCase()}\n\n`;
      out += `${ep.content}\n\n`;
      out += `===\n\n`;
    });

    return out.trim();
  }

  private formatDraftAsMarkdown(draft: Draft): string {
    let md = `# ${draft.title || 'Untitled Saga Draft'}\n\n`;
    md += `**Genre**: ${draft.genre || 'General Fiction'}  \n`;
    md += `**Last Edited**: ${new Date(draft.updatedAt).toLocaleDateString()}  \n\n`;

    if (draft.blurb) {
      md += `> ${draft.blurb}\n\n---\n\n`;
    }

    draft.episodes.forEach((ep, i) => {
      md += `## Episode ${i + 1}: ${ep.title || `Part ${i + 1}`}\n\n`;
      md += `${ep.content}\n\n`;
      md += `---\n\n`;
    });

    if (draft.canonFacts && draft.canonFacts.length > 0) {
      md += `## 📜 Master Story Canon Facts\n\n`;
      draft.canonFacts.forEach(f => {
        md += `- **[Ep ${f.episodeNumber}] (${f.subject})**: ${f.text} *(Ref: "${f.quote}")*\n`;
      });
      md += `\n---\n\n`;
    }

    if (draft.voiceNotes && draft.voiceNotes.length > 0) {
      md += `## 🎙️ Character Voice Notes\n\n`;
      draft.voiceNotes.forEach(v => {
        md += `- **${v.character}**: ${v.style}\n`;
      });
      md += `\n---\n\n`;
    }

    md += `*Exported from Canon Story Studio — Continuity Engine*\n`;
    return md;
  }

  private formatDraftAsText(draft: Draft): string {
    let txt = `=================================================================\n`;
    txt += `${(draft.title || 'UNTITLED DRAFT').toUpperCase()}\n`;
    txt += `Genre: ${draft.genre || 'Fiction'} | Status: Working Draft\n`;
    txt += `=================================================================\n\n`;

    draft.episodes.forEach((ep, i) => {
      txt += `EPISODE ${i + 1}: ${(ep.title || 'UNTITLED').toUpperCase()}\n\n`;
      txt += `${ep.content}\n\n`;
      txt += `-----------------------------------------------------------------\n\n`;
    });

    return txt;
  }

  private slugify(text: string): string {
    return text
      .toLowerCase()
      .trim()
      .replace(/[^\w\s-]/g, '')
      .replace(/[\s_-]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'story';
  }
}

export const exportService = new ExportService();
